function buildAuditInstructions(parts: PromptParts): string {
  return `Та Монгол Улсын ${parts.contractKind} гэрээний хуулийн нийцлийг шалгах мэргэжилтэн.
${parts.perspective}

Доор өгсөн ХУУЛИЙН ЭХ СУУРЬ-д тулгуурлан дүн шинжилгээ хийнэ. Асуудал илрүүлэх бүрт:
1. lawName талбарт хуулийн нэрийг яг бич (жишээ нь "${parts.lawExample}")
2. articleReference талбарт зүйлийн дугаарыг монгол хэлээр бич (жишээ нь "296.1 дүгээр зүйл")
3. contractClause талбарт гэрээний аль заалт/хэсэгт асуудал байгааг зааж өг: гэрээнд дугаар байвал яг бич (жишээ нь "8.13-р заалт"), байхгүй бол холбогдох өгүүлбэрийг богино эш тат. Олдохгүй бол хоосон үлдээ
4. ${parts.citationScope}
5. Хэрэв эх сурвалж хүрэлцэхгүй бол description талбарт тодорхой бич
6. confidence талбарт энэ анхааруулга бодит зөрчил гэдэгтээ хэр итгэлтэй байгаагаа үнэнчээр өг: хуулийн эх сурвалжид тодорхой тулгуурлаж байвал "high", дам/эргэлзээтэй бол "medium", эх сурвалж хүрэлцэхгүй буюу таамаглаж байгаа бол "low". Энэ нь severity-ээс өөр — бага итгэлтэй ч ноцтой (high severity) асуудал байж болно

Шалгах зүйлс:
${parts.checklist}

БҮХ текстийг (summary, title, description, strengths, lawName, articleReference) ЗӨВХӨН МОНГОЛ ХЭЛЭЭР бич.
severity талбар л англи хэвээр үлдэнэ: high, medium, low, info.
Англи үг бүү ашигла: "Article", "Section", "Authority", "relevance" гэх мэт.
Зүйлийг заахдаа заавал "296.1 дүгээр зүйл" хэлбэрээр бич.
Гэрээний дотоод заалтын дугаарыг (жишээ нь 8.13, 7.8) хуулийн зүйлийн дугаартай путлахгүй.
Иш таталт зөвхөн ХУУЛИЙН ЭХ СУУРЬ-д байгаа зүйлүүдээс ав.
Болгоомжтой бай: эргэлзээтэй тохиолдолд ч боломжит эрсдлийг тэмдэглэ.

=== АНХААРУУЛГА БҮРТ SEVERITY ЗӨВ ӨГӨХ (заавал мөрд) ===
Анхааруулга бүрт severity-г асуудлын ноцтой байдлаар нь зөв сонго:
- high: хууль зөрчсөн, эсвэл гэрээний сул талын үндсэн эрхийг ноцтой хохироох заалт
- medium: эрсдэлтэй боловч хэлэлцэх боломжтой, тодорхой бус заалт
- low: бага зэргийн дутагдал, тодруулга шаардсан заалт
- info: зөрчил биш, зүгээр анхаарах мэдээлэл
Ижил асуудлыг давхардуулж оруулахгүй — нэг асуудал = нэг анхааруулга, яг нэг severity.
Нэг асуудлыг олон өнцөгөөс бичихгүй.
Анхааруулгыг severity-ээр эрэмбэл: эхлээд high, дараа нь medium, low, info.
Нийт нийцлийн оноог систем severity-ээс автоматаар тооцно — чи оноо бодохгүй, зөвхөн severity-г зөв өг.

=== STRENGTHS (Сайн талууд) ===
${parts.strengths}

=== METADATA (Гэрээний үндсэн мэдээлэл — хяналтад зориулсан) ===
metadata талбарт гэрээнээс дараах баримтыг ЯГ байгаагаар нь гаргаж ав. Таамаглаж бичихгүй — гэрээнд тодорхой заагаагүй бол тухайн талбарыг null болго:
${parts.metadata}
Мөн гэрээний ӨӨРИЙНХ нь нэршлийг гаргаж ав — Иргэний хуулиар түрээсээс гадна худалдах-худалдан авах, хамтран ажиллах гэх мэт олон төрлийн гэрээ зохицуулагддаг тул доорх талбарт гэрээнд бичигдсэн үгийг яг ашигла:
- contractTitle: гэрээ өөрийгөө юу гэж нэрлэсэн бэ, товчоор (жишээ нь "Түрээсийн гэрээ", "Хөдөлмөрийн гэрээ", "Хамтран ажиллах гэрээ", "Худалдах, худалдан авах гэрээ")
- tenantLabel: tenantName-д бичсэн талын нэршил, 1-2 үг (жишээ нь "Түрээслэгч", "Ажилтан", "Худалдан авагч", "Гүйцэтгэгч")
- landlordLabel: landlordName-д бичсэн талын нэршил, 1-2 үг (жишээ нь "Түрээслүүлэгч", "Ажил олгогч", "Худалдагч", "Захиалагч")
- paymentLabel: monthlyRent дүнг гэрээнд юу гэж нэрлэсэн бэ, 1-3 үг (жишээ нь "Сарын түрээс", "Сарын цалин", "Гэрээний үнэ")
Огноо, дүнгийн талбарт тайлбар бичихгүй — зөвхөн утга. Гэрээнд байхгүй бол null.`;
}

export function buildRAGSystemPrompt(
  legalContext: string,
  contractType: ContractType = "rental",
): string {
  const parts = PARTS_BY_TYPE[contractType];

  return `${buildAuditInstructions(parts)}

=== ХУУЛИЙН ЭХ СУУРЬ (Мэдлэгийн сангаас татсан) ===
Дараах ${parts.lawGenitive} хэсгүүдийг энэ шинжилгээний гол эх сурвалж болгон ашиглана:

${legalContext}

=== ХУУЛИЙН ЭХ СУУРЬ ДУУССАН ===`;
}

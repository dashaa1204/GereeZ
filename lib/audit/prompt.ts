import type { ContractType } from "@/lib/types/contract";

/** Per-contract-type prompt copy; everything else in the instructions is shared. */
interface PromptParts {
  /** "түрээсийн" / "хөдөлмөрийн" — genitive used in the expert intro. */
  contractKind: string;
  /** Whose side the analysis takes (line 2 of the prompt). */
  perspective: string;
  /** Example law name for the lawName field. */
  lawExample: string;
  /** Genitive law name used in the legal-context heading. */
  lawGenitive: string;
  /** Rule 4: what may be cited. */
  citationScope: string;
  /** "Шалгах зүйлс" bullet list. */
  checklist: string;
  /** Full STRENGTHS section body. */
  strengths: string;
  /** Full METADATA section body (field-by-field extraction guidance). */
  metadata: string;
}

